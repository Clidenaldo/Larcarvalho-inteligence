/** Static guidance reviewed against packages/shared/src/contracts. Never used for validation. */
export interface FormHelpContent {
  readonly title: string;
  readonly description: string;
  readonly howToFill: string;
  readonly example: string;
  readonly validation: string;
  readonly impact: string;
  readonly warning?: string;
  readonly learnMoreUrl?: `/ajuda${string}`;
}

const noPromise =
  'Use uma fonte oficial e vigente. Simulações não garantem contemplação, rendimento ou aprovação.';
const versioned =
  'Baseie o dado na fonte comercial válida e registre a nova versão da regra quando as condições mudarem.';
const help = (
  title: string,
  description: string,
  howToFill: string,
  example: string,
  validation: string,
  impact: string,
  warning?: string,
): FormHelpContent => ({
  title,
  description,
  howToFill,
  example,
  validation,
  impact,
  ...(warning ? { warning } : {}),
});
const money = (
  title: string,
  description: string,
  impact: string,
  positive = false,
) =>
  help(
    title,
    description,
    'Informe reais, sem R$ nem separador de milhar; use até duas casas decimais.',
    '150000.00',
    positive
      ? 'Informe um valor maior que zero; respeite os limites indicados no campo.'
      : 'Não use valor negativo. Um campo opcional vazio indica dado não informado, não valor zero.',
    impact,
    noPromise,
  );
const percent = (title: string, description: string, impact: string) =>
  help(
    title,
    description,
    'Informe o número do percentual sem o símbolo %. Não converta reais em percentual sem conhecer a base.',
    '2.50 significa 2,5%.',
    'De 0 a 100. Respeite a precisão indicada pelo campo; contratos comerciais aceitam até seis casas decimais.',
    impact,
    `${versioned} ${noPromise}`,
  );
const text = (
  title: string,
  description: string,
  example: string,
  validation: string,
  impact: string,
) =>
  help(
    title,
    description,
    'Use texto claro, fiel ao documento ou ao cadastro de origem.',
    example,
    validation,
    impact,
  );
const choice = (
  title: string,
  description: string,
  example: string,
  impact: string,
) =>
  help(
    title,
    description,
    'Escolha uma das opções exibidas. Use a opção vazia apenas quando o campo permitir.',
    example,
    'Somente as opções disponíveis são aceitas; vínculos e permissões continuam sendo verificados ao salvar.',
    impact,
  );
const date = (
  title: string,
  description: string,
  impact: string,
  validation = 'Use uma data válida; campos opcionais podem ficar vazios.',
) =>
  help(
    title,
    description,
    'Use o calendário ou digite a data no formato exibido pelo navegador.',
    '10/09/2026 (armazenado como 2026-09-10).',
    validation,
    impact,
  );
const toggle = (title: string, description: string, impact: string) =>
  help(
    title,
    description,
    'Marque para ativar esta opção; desmarque para não aplicá-la.',
    'Marcado: opção ativada.',
    'É uma escolha sim/não. As permissões e regras existentes continuam valendo.',
    impact,
  );


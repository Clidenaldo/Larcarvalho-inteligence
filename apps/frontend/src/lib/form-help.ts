/** Only the existing internal help page and simple anchors are linkable. */
export function safeHelpUrl(value: string | undefined): string | undefined {
  return value && /^\/ajuda(?:#[a-zA-Z0-9_-]+)?$/.test(value)
    ? value
    : undefined;
}
